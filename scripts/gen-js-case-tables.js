// Generates src/Dotenvx.Core/Interop.DotenvxJs/Helpers/JsCaseTables.cs: every code point whose JavaScript toUpperCase / toLowerCase result differs
// from itself (including the multi-character expansions such as "ß" -> "SS"). .NET's invariant casing is a simple one-to-one mapping and differs
// for these. Run: node scripts/gen-js-case-tables.js
const fs = require('fs')
const path = require('path')

const entries = (convert) => {
  const out = []
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue
    const ch = String.fromCodePoint(cp)
    if (cp === 0x3a3 && convert === 'lower') continue // final sigma depends on context: handled in code
    const mapped = convert === 'upper' ? ch.toUpperCase() : ch.toLowerCase()
    if (mapped !== ch) out.push(cp.toString(16) + ':' + [...mapped].map(c => c.codePointAt(0).toString(16)).join(','))
  }
  return out
}

const chunk = list => {
  const lines = []
  for (let i = 0; i < list.length; i += 12) lines.push('        "' + list.slice(i, i + 12).join(' ') + '"')
  return lines.join(',\n')
}

const upper = entries('upper')
const lower = entries('lower')
const source = `namespace Dotenvx.Interop.DotenvxJs.Helpers;

// <auto-generated> by scripts/gen-js-case-tables.js (Node ${process.version}, Unicode ${process.versions.unicode}); do not edit </auto-generated>
internal static partial class JsCase
{
    // "codepoint:mapped,codepoints" in hex
    private static readonly string[] UpperData =
    [
${chunk(upper)}
    ];

    private static readonly string[] LowerData =
    [
${chunk(lower)}
    ];
}
`
fs.writeFileSync(path.join(__dirname, '..', 'src', 'Dotenvx.Core', 'Interop.DotenvxJs', 'Helpers', 'JsCaseTables.cs'), source)
console.log('upper', upper.length, 'lower', lower.length)
